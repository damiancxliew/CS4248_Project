"""Generate C7 mean/sample-standard-deviation CSV and LaTeX tables.

Usage (repository environment, PYTHONPATH=src):
  python scripts/make_tables.py --runs-dir results/runs --out-dir results/tables
  python scripts/make_tables.py --literature --out-dir results/tables

Groups retain system, variant, split, question count, parameter count, GPU,
git SHA and resolved config except top-level seed/run_id. Thus different
encoders, decoding settings, data paths and training settings never pool.
Null metrics stay unavailable; singleton standard deviations are undefined.
Outputs include seed counts and IDs, without claiming three-seed completeness.
"""
import argparse
import csv
import json
from pathlib import Path
from statistics import mean, stdev

from qa.eval.run_eval import METRICS, validate_record

GROUP_FIELDS = ("system", "variant", "split", "n", "params_M", "gpu", "git_sha")


def make_literature_table(out_dir="results/tables"):
    """X10 source transcription, NOT C7 experiments; never pool with run records.

    EM/F1 are percentages on official SQuAD v1.1 dev, single models.
    None means not verified for that setting (not zero). Verification and
    historical/non-comparable results live in docs/tasks/xinhui.md section 9.
    This is a curated transcription from publications, not a benchmark rerun.
    """
    fields = ("model", "em", "f1", "citation", "url", "locator", "caveat")
    records = [
        ("Logistic regression", None, None, "rajpurkar2016squad",
         "https://aclanthology.org/D16-1264.pdf", "Table 5, PDF p.8; p.2 footnote 1",
         "Original paper reports v1.0, not verified v1.1 dev"),
        ("BiDAF", 67.7, 77.3, "seo2017bidaf",
         "https://arxiv.org/pdf/1611.01603", "Table 1b, PDF p.6",
         "Single; GloVe embeddings; not the ensemble or test row"),
        ("BERT-base", 80.8, 88.5, "devlin2019bert",
         "https://aclanthology.org/N19-1423.pdf", "Table 2, PDF p.7 (4177)",
         "Single; no TriviaQA; BooksCorpus/Wikipedia pretraining"),
        ("BERT-large", 84.1, 90.9, "devlin2019bert",
         "https://aclanthology.org/N19-1423.pdf", "Table 2, PDF p.7 (4177)",
         "Single; no TriviaQA; not whole-word-masking BERT"),
        ("SpanBERT-base", None, 92.4, "joshi2020spanbert",
         "https://github.com/facebookresearch/SpanBERT", "README Results table, starred base row",
         "Author-reported dev F1 only; EM not supplied; cased base checkpoint"),
        ("SpanBERT-large", None, None, "joshi2020spanbert",
         "https://arxiv.org/pdf/1907.10529", "Table 1, PDF p.6",
         "Headline EM/F1 is test; no verified dev pair in checked sources"),
        ("XLNet-large", 89.7, 95.1, "yang2019xlnet",
         "https://arxiv.org/pdf/1906.08237v2", "Table 3, PDF p.8; section 3.3",
         "Revised full-data setting; differs from earlier 89.0/94.5 in RoBERTa Table 6"),
        ("RoBERTa-large", 88.9, 94.6, "liu2019roberta",
         "https://arxiv.org/pdf/1907.11692", "Table 6, PDF p.9; section 5.2",
         "Single, no QA data augmentation; broader pretraining than BERT"),
        ("DeBERTa-base", 87.2, 93.1, "he2021deberta",
         "https://arxiv.org/pdf/2006.03654", "Table 3, PDF p.7",
         "Original DeBERTa, not V3; source columns are F1/EM"),
        ("DeBERTa-large", 90.1, 95.5, "he2021deberta",
         "https://arxiv.org/pdf/2006.03654", "Table 2, PDF p.7",
         "Original DeBERTa; source F1/EM reversed here; different pretraining from V3"),
        ("DeBERTaV3-base", None, None, "he2023debertav3",
         "https://arxiv.org/pdf/2111.09543", "Tables 4-5, PDF pp.7-8; official README NLU table",
         "Paper reports SQuAD v2.0; no verified v1.1 dev pair in checked sources"),
    ]
    rows = [dict(zip(fields, values)) for values in records]
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "literature_squad11.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    lines = ["% Generated by scripts/make_tables.py --literature; do not edit.",
             "% Provenance/caveats: literature_squad11.csv and xinhui.md section 9.",
             r"\begin{tabular}{@{}p{0.65\columnwidth}rr@{}}", r"\toprule",
             r"Published model & EM & F1 \\", r"\midrule"]
    for row in rows:
        scores = ["--" if row[m] is None else f"{row[m]:.1f}" for m in ("em", "f1")]
        lines.append(_tex(row["model"]) + r" \citep{" + row["citation"] + "} & " +
                     " & ".join(scores) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\par\noindent SQuAD v1.1 dev, single models; -- = unverified.",
              r"LR's original results use v1.0; SpanBERT-base has dev F1 only;",
              r"SpanBERT-large reports test; V3 reports v2.0. Pretraining differs.",
              r"Internal validation results are excluded."]
    (out_dir / "literature_squad11.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rows


def aggregate_records(records):
    groups, run_ids = {}, set()
    for record in records:
        validate_record(record)
        if record["run_id"] in run_ids:
            raise ValueError(f"duplicate run_id: {record['run_id']}")
        run_ids.add(record["run_id"])
        cfg = {k: v for k, v in record["config"].items() if k not in ("seed", "run_id")}
        identity = {k: record[k] for k in GROUP_FIELDS}
        identity["config"] = cfg
        key = json.dumps(identity, sort_keys=True, allow_nan=False)
        groups.setdefault(key, []).append(record)
    rows = []
    for key, group in sorted(groups.items()):
        seeds = [r["seed"] for r in group]
        if len(set(seeds)) != len(seeds):
            raise ValueError("duplicate seed in a compatible group; select one run per seed")
        row = json.loads(key)
        row["config"] = json.dumps(row["config"], sort_keys=True, ensure_ascii=False)
        row.update(seed_count=len(group), seeds=json.dumps(sorted(seeds, key=str)),
                   run_ids=json.dumps(sorted(r["run_id"] for r in group)))
        for metric in METRICS:
            values = [r[metric] for r in group if r[metric] is not None]
            if values and len(values) != len(group):
                raise ValueError(f"mixed null/present {metric} within a group")
            row[f"{metric}_mean"] = mean(values) if values else None
            row[f"{metric}_std"] = stdev(values) if len(values) > 1 else None
        rows.append(row)
    return rows


def _tex(value):
    escape = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
              "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
              "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(escape.get(c, c) for c in str(value))


def make_tables(runs_dir="results/runs", out_dir="results/tables"):
    paths = sorted(Path(runs_dir).glob("*.json"))
    if not paths:
        raise ValueError("no C7 run records; no experiment tables generated")
    records = [json.loads(p.read_text(encoding="utf-8")) for p in paths]
    rows = aggregate_records(records)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    fields = [*GROUP_FIELDS, "config", "seed_count", "seeds", "run_ids",
              *(f"{m}_{s}" for m in METRICS for s in ("mean", "std"))]
    with (out_dir / "run_summary.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    lines = ["% Generated; sample std (ddof=1), NA = unavailable/undefined.",
             r"\begin{tabular}{llllr" + "r" * len(METRICS) + "}", r"\hline",
             "Group & System & Variant & Split & Seeds & " +
             " & ".join(_tex(m) for m in METRICS) + r" \\", r"\hline"]
    for idx, row in enumerate(rows, 1):
        cells = [str(idx), *(_tex(row[k]) for k in ("system", "variant", "split")),
                 str(row["seed_count"])]
        for metric in METRICS:
            avg, sd = row[f"{metric}_mean"], row[f"{metric}_std"]
            cells.append("NA" if avg is None else
                         f"{avg:.2f} $\\pm$ " + ("NA" if sd is None else f"{sd:.2f}"))
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\hline", r"\end{tabular}"]
    # Full group identities let identical-looking labels be traced to the CSV.
    lines += [f"% Group {i}: " + _tex(json.dumps(row, sort_keys=True, ensure_ascii=False))
              for i, row in enumerate(rows, 1)]
    (out_dir / "run_summary.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rows


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--runs-dir", default="results/runs")
    parser.add_argument("--out-dir", default="results/tables")
    parser.add_argument("--literature", action="store_true",
                        help="generate source-verified X10 literature only (no C7 inputs)")
    args = parser.parse_args(argv)
    if args.literature:
        rows = make_literature_table(args.out_dir)
        print(f"Generated {len(rows)} literature rows in {args.out_dir}")
        return
    rows = make_tables(args.runs_dir, args.out_dir)
    print(f"Generated {len(rows)} compatible groups in {args.out_dir}")


if __name__ == "__main__":
    main()
